using WindFlow.Core;
using WindFlow.App.Import;

namespace WindFlow.App;

/// <summary>Import robustness checks: glass panes dropped by material, curtain walls kept, IfcOpenShell OBJ read as Z-up.</summary>
public static partial class SelfCheck
{
    static void Checks_Import(List<(string Name, bool Ok, string Detail)> feature)
    {
        string[] yes = ["IfcWindow", "Glass", "Clear glazing", "IfcWindow-Glazing", "Window_frame_glass", "Pane 3"];
        string[] no = ["IfcWall", "IfcCurtainWall", "Curtain wall glass panel", "IfcPlate", "IfcSurfaceStyleRendering-12", "DefaultMaterial", "ifcdoor", "IfcDoor", "Glass wool", "Fibreglass insulation", "GFRC panel"];
        bool namesOk = yes.All(MeshImport.IsPaneName) && no.All(n => !MeshImport.IsPaneName(n));
        feature.Add(("Import: pane material names match as whole words (IfcWindow, glass, glazing, pane); doors, walls, curtain walls, plates, glass wool, fibreglass and GFRC do not", namesOk,
            $"missed [{string.Join(", ", yes.Where(n => !MeshImport.IsPaneName(n)))}] · wrongly matched [{string.Join(", ", no.Where(MeshImport.IsPaneName))}]"));

        // Two unit squares in one OBJ: an opaque wall material and a transparent one (d 0.3). Written by "IfcOpenShell" so the axis reads Z-up.
        string stem = Path.Combine(Path.GetTempPath(), $"windflow-selfcheck-panes-{System.Environment.ProcessId}");
        try
        {
            File.WriteAllText(stem + ".mtl", "newmtl wall\nKd 0.5 0.5 0.5\nnewmtl clear\nKd 0.7 0.8 0.9\nd 0.3\n");
            File.WriteAllText(stem + ".obj",
                "# File generated by IfcOpenShell 0.8\nmtllib " + Path.GetFileName(stem) + ".mtl\n" +
                "v 0 0 0\nv 1 0 0\nv 1 0 1\nv 0 0 1\nv 2 0 0\nv 3 0 0\nv 3 0 1\nv 2 0 1\n" +
                "g a\nusemtl wall\nf 1 2 3 4\ng b\nusemtl clear\nf 5 6 7 8\n");
            var g = MeshImport.Load(stem + ".obj");
            var s2 = new ImportSettings { YUpToZUp = false, DetectRooms = false, RemovePanes = false };
            var all = MeshImport.Build(g, s2);
            var s3 = new ImportSettings { YUpToZUp = false, DetectRooms = false };
            var cut = MeshImport.Build(g, s3);
            feature.Add(("Import: a synthetic model with one transparent material loses only that pane, keeps both with RemovePanes off, and notes it",
                g.Meshes.Count == 2 && g.PaneMeshIds.Count == 1 && cut.Obstacles.Count == 1 && all.Obstacles.Count == 2 &&
                s3.Notes.Any(n => n.StartsWith("removed 1 m² of glass (1 transparent material)", StringComparison.Ordinal)) && s2.Notes.Count == 0,
                $"meshes {g.Meshes.Count}, pane meshes {g.PaneMeshIds.Count}, after removal {cut.Obstacles.Count}, off {all.Obstacles.Count} · {string.Join(" | ", s3.Notes)}"));
            bool zup = !MeshImport.GuessYUp(g, 1f, out string why);
            feature.Add(("Import: an OBJ whose first line says IfcOpenShell is read as Z-up with the reason given", zup && why.Contains("IfcOpenShell"), $"Z-up {zup} · {why}"));
            File.WriteAllText(stem + ".obj", "# WaveFront *.obj file (generated by Autodesk ATF)\nv 0 0 0\nv 10 0 0\nv 10 10 0\nv 0 10 0\nf 1 2 3 4\n");
            var atf = MeshImport.Load(stem + ".obj");
            bool atfZ = !MeshImport.GuessYUp(atf, 1f, out string atfWhy);
            feature.Add(("Import: an OBJ whose first line says Autodesk ATF (Revit) is read as Z-up and feet", atfZ && MeshImport.GuessUnit(atf) == 3 && atfWhy.Contains("Autodesk ATF"), $"Z-up {atfZ} · unit {MeshImport.Units[MeshImport.GuessUnit(atf)].Label} · {atfWhy}"));
        }
        finally { foreach (var ext in new[] { ".obj", ".mtl" }) File.Delete(stem + ext); }

        // SketchUp: "# File units = inches" is a declared unit; a window/door group is removed, a car door and a big "frame" wall are not.
        try
        {
            File.WriteAllText(stem + ".obj", string.Join("\n", new[] { "# Exported from SketchUp", "# File units = inches", "g Wall House1", "v 0 0 0", "v 300 0 0", "v 300 0 200", "v 0 0 200", "f 1 2 3 4", "g Window_3lite House1", "v 10 0 10", "v 40 0 10", "v 40 0 40", "f 5 6 7", "g Door_RF Vehicles_VW", "v 10 5 10", "v 40 5 10", "v 40 5 40", "f 8 9 10", "g frame wall", "v 0 9 0", "v 300 9 0", "v 300 9 200", "f 11 12 13" }) + "\n");
            var sk = MeshImport.Load(stem + ".obj");
            var ss = new ImportSettings { YUpToZUp = false, DetectRooms = false, MetresPerUnit = MeshImport.Units[MeshImport.GuessUnit(sk)].Metres };
            var skb = MeshImport.Build(sk, ss);
            feature.Add(("Import: an OBJ with \"# File units = inches\" (SketchUp) starts on inches, and only the window group is removed",
                MeshImport.GuessUnit(sk) == 4 && sk.WrittenBySketchUp && sk.Meshes.Count == 4 && skb.Obstacles.Count == 3 && ss.Notes.Any(n => n.StartsWith("1 window/door component removed", StringComparison.Ordinal)),
                $"unit {MeshImport.Units[MeshImport.GuessUnit(sk)].Label} · meshes {sk.Meshes.Count} → {skb.Obstacles.Count} · {string.Join(" | ", ss.Log)}"));
        }
        finally { foreach (var ext in new[] { ".obj", ".mtl" }) File.Delete(stem + ext); }

        // Kept, not removed: a see-through curtain-wall material (opacity 0.3), glass wool (opaque) and an IfcDoor; only the window glass goes.
        string stem2 = stem + "-kept";
        try
        {
            File.WriteAllText(stem2 + ".mtl", "newmtl curtain_glass\nKd 0.7 0.8 0.9\nd 0.3\nnewmtl Glass_wool\nKd 0.9 0.9 0.5\nnewmtl IfcDoor\nKd 0.5 0.3 0.1\nnewmtl IfcWindow\nKd 0.7 0.8 0.9\n");
            File.WriteAllText(stem2 + ".obj",
                "# File generated by IfcOpenShell 0.8\nmtllib " + Path.GetFileName(stem2) + ".mtl\n" +
                "v 0 0 0\nv 1 0 0\nv 1 0 1\nv 0 0 1\nv 2 0 0\nv 3 0 0\nv 3 0 1\nv 2 0 1\nv 4 0 0\nv 5 0 0\nv 5 0 1\nv 4 0 1\nv 6 0 0\nv 7 0 0\nv 7 0 1\nv 6 0 1\n" +
                "g a\nusemtl curtain_glass\nf 1 2 3 4\ng b\nusemtl Glass_wool\nf 5 6 7 8\ng c\nusemtl IfcDoor\nf 9 10 11 12\ng d\nusemtl IfcWindow\nf 13 14 15 16\n");
            var g2 = MeshImport.Load(stem2 + ".obj");
            feature.Add(("Import: curtain glass with opacity < 1, glass wool and an IfcDoor are kept; only the IfcWindow material is removed", g2.Meshes.Count == 4 && g2.PaneMeshIds.Count == 1,
                $"meshes {g2.Meshes.Count}, pane meshes {g2.PaneMeshIds.Count}"));
        }
        finally { foreach (var ext in new[] { ".obj", ".mtl" }) File.Delete(stem2 + ext); }

        // A 8 x 6 m house with a 2 x 1 m window in its south wall (sill 1 m), drawn turned 30° in plan: the import straightens it, keeps the window,
        // and turns NorthDeg so a wind from true north (file +Y) still meets the house at the same angle (rotated by -30° into the building's own frame).
        string stem3 = stem + "-rot";
        try
        {
            var flatG = MeshImport.Load(WriteHouse(stem3, 0));
            var turnedG = MeshImport.Load(WriteHouse(stem3, 30));
            ImportSettings Mk(ImportedGeometry gg, bool align) { var st = new ImportSettings { YUpToZUp = false, AlignToGrid = align }; st.Storeys = MeshImport.GuessStoreys(gg.Meshes, st); return st; }
            var flat = MeshImport.Build(flatG, Mk(flatG, true));
            var flatOff = MeshImport.Build(flatG, Mk(flatG, false));
            var sTurn = Mk(turnedG, true);
            var turned = MeshImport.Build(turnedG, sTurn);
            bool same = flat.NorthDeg == 0 && flat.Obstacles.Count == flatOff.Obstacles.Count &&
                        flat.Obstacles.Zip(flatOff.Obstacles).All(p => p.First.Vertices.SequenceEqual(p.Second.Vertices));
            var wind = SolverRun.WindVector(0, 1, turned.NorthDeg);
            var want = new System.Numerics.Vector2(-0.5f, -0.8660254f);   // the file-frame wind (0, -1) seen in the building's own frame (turned by -30°)
            bool windOk = (wind - want).Length() < 0.02f;
            bool straight = MeshImport.DominantWallTurn(turned.Obstacles) is null;
            var det = RoomDetect.Detect(turned, 1);
            feature.Add(("Import: a house drawn turned 30° is straightened (walls on the axes, one window found) with north turned so the wind keeps its angle to the house; an axis-aligned house is untouched",
                same && straight && windOk && turned.NorthDeg is > 29.5f and < 30.5f && det.Openings.Any(o => o.Kind == OpeningKind.Window) && sTurn.Notes.Any(n => n.StartsWith("Turned the model 30", StringComparison.Ordinal)),
                $"axis-aligned unchanged {same} · NorthDeg {turned.NorthDeg:0.0} · wind ({wind.X:0.00}, {wind.Y:0.00}) want ({want.X:0.00}, {want.Y:0.00}) · straight {straight} · openings {string.Join(", ", det.Openings.Select(o => o.Name))}"));
        }
        finally { File.Delete(stem3 + ".obj"); }
    }

    /// <summary>Writes a Z-up OBJ of a box house (floor, roof, four 0.2 m walls, a 2 x 1 m window hole in the y = 0 wall) turned <paramref name="deg"/> degrees counter-clockwise about its corner.</summary>
    static string WriteHouse(string stem, double deg)
    {
        double c = Math.Cos(deg * Math.PI / 180), s = Math.Sin(deg * Math.PI / 180);
        var sb = new System.Text.StringBuilder("# File generated by IfcOpenShell 0.8\n");
        int n = 0;
        void Box(double x0, double y0, double z0, double x1, double y1, double z1)
        {
            for (int i = 0; i < 8; i++)
            {
                double x = (i & 1) == 0 ? x0 : x1, y = (i & 2) == 0 ? y0 : y1, z = (i & 4) == 0 ? z0 : z1;
                sb.Append(FormattableString.Invariant($"v {c * x - s * y:0.#####} {s * x + c * y:0.#####} {z}\n"));
            }
            sb.Append($"g b{n}\n");
            foreach (var f in new[] { new[] { 0, 2, 3, 1 }, new[] { 4, 5, 7, 6 }, new[] { 0, 1, 5, 4 }, new[] { 2, 6, 7, 3 }, new[] { 0, 4, 6, 2 }, new[] { 1, 3, 7, 5 } })
                sb.Append("f " + string.Join(" ", f.Select(k => n * 8 + k + 1)) + "\n");
            n++;
        }
        Box(0, 0, 0, 8, 6, 0.2); Box(0, 0, 2.8, 8, 6, 3);                                   // floor, roof
        Box(0, 0, 0.2, 3, 0.2, 2.8); Box(5, 0, 0.2, 8, 0.2, 2.8); Box(3, 0, 0.2, 5, 0.2, 1.2); Box(3, 0, 2.2, 5, 0.2, 2.8);   // south wall around the window
        Box(0, 5.8, 0.2, 8, 6, 2.8); Box(0, 0.2, 0.2, 0.2, 5.8, 2.8); Box(7.8, 0.2, 0.2, 8, 5.8, 2.8);
        File.WriteAllText(stem + ".obj", sb.ToString());
        return stem + ".obj";
    }
}
