/// <summary>Q-criterion Q = ½(‖Ω‖² − ‖S‖²) from central differences of the velocity; positive = vortex core.</summary>
public static class Vorticity
{
    public static float[] Q(FlowField field)
    {
        var g = field.Grid;
        int nx = g.Nx, ny = g.Ny, nz = g.Nz;
        var q = new float[nx * ny * nz];

        Parallel.For(0, nz, z =>
        {
            for (int y = 0; y < ny; y++)
            for (int x = 0; x < nx; x++)
            {
                int idx = g.Index(x, y, z);
                if (g.Cell[idx] == VoxelGrid.Solid) { q[idx] = float.NaN; continue; }

                var dux = Deriv(field, g, x, y, z, 1, 0, 0);   // d(ux,uy,uz)/dx
                var duy = Deriv(field, g, x, y, z, 0, 1, 0);   // d(ux,uy,uz)/dy
                var duz = Deriv(field, g, x, y, z, 0, 0, 1);   // d(ux,uy,uz)/dz

                // Velocity gradient tensor A[i,j] = d(u_i)/d(x_j).
                float a00 = dux.X, a01 = duy.X, a02 = duz.X;
                float a10 = dux.Y, a11 = duy.Y, a12 = duz.Y;
                float a20 = dux.Z, a21 = duy.Z, a22 = duz.Z;

                double s2 = 0, w2 = 0;
                Sum(a00, a00); Sum(a01, a10); Sum(a02, a20);
                Sum(a10, a01); Sum(a11, a11); Sum(a12, a21);
                Sum(a20, a02); Sum(a21, a12); Sum(a22, a22);
                void Sum(float aij, float aji)
                {
                    float s = 0.5f * (aij + aji);
                    float w = 0.5f * (aij - aji);
                    s2 += (double)s * s;
                    w2 += (double)w * w;
                }
                q[idx] = (float)(0.5 * (w2 - s2));
            }
        });

        return q;
    }

    // Central difference of velocity along one axis (dxStep,dyStep,dzStep) unit step; one-sided at a solid
    // neighbour or the grid boundary; returns 0 if neither neighbour is usable.
    static Vector3 Deriv(FlowField f, VoxelGrid g, int x, int y, int z, int dxStep, int dyStep, int dzStep)
    {
        float h = g.Dx;
        int xp = x + dxStep, yp = y + dyStep, zp = z + dzStep;
        int xm = x - dxStep, ym = y - dyStep, zm = z - dzStep;
        bool pIn = xp >= 0 && xp < g.Nx && yp >= 0 && yp < g.Ny && zp >= 0 && zp < g.Nz;
        bool mIn = xm >= 0 && xm < g.Nx && ym >= 0 && ym < g.Ny && zm >= 0 && zm < g.Nz;
        int idxP = pIn ? g.Index(xp, yp, zp) : -1;
        int idxM = mIn ? g.Index(xm, ym, zm) : -1;
        bool pOk = pIn && g.Cell[idxP] != VoxelGrid.Solid;
        bool mOk = mIn && g.Cell[idxM] != VoxelGrid.Solid;
        int idx0 = g.Index(x, y, z);
        var u0 = new Vector3(f.Ux[idx0], f.Uy[idx0], f.Uz[idx0]);

        if (pOk && mOk)
        {
            var up = new Vector3(f.Ux[idxP], f.Uy[idxP], f.Uz[idxP]);
            var um = new Vector3(f.Ux[idxM], f.Uy[idxM], f.Uz[idxM]);
            return (up - um) / (2 * h);
        }
        if (pOk)
        {
            var up = new Vector3(f.Ux[idxP], f.Uy[idxP], f.Uz[idxP]);
            return (up - u0) / h;
        }
        if (mOk)
        {
            var um = new Vector3(f.Ux[idxM], f.Uy[idxM], f.Uz[idxM]);
            return (u0 - um) / h;
        }
        return Vector3.Zero;
    }
}
